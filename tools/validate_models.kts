import com.brewpos.cafe.*
val base = Product(id=1, name="Latte", category="Coffee", priceCents=15000, stock=10)
val large = CartLine(base, "Large", 3000, listOf(Extra("Oat",3000)), 2)
check(large.unitCents == 21000)
check(large.lineCents == 42000)
check(large.options == "Large, Oat")
val totals = CartMath.totals(listOf(large), 2000)
check(totals.subtotal == 42000 && totals.discount == 2000 && totals.payable == 40000)
check(CartMath.change(40000, 50000, "Cash") == 10000)
check(runCatching { CartMath.change(40000, 39999, "Cash") }.isFailure)
check(CartMath.totals(listOf(large), 999999).payable == 0)
check(parseMoney("123.45") == 12345)
check(parseMoney("0.01") == 1)
check(parseMoney("12.345") == null)
check(parseMoney("-4") == null)
check(peso(12345) == "₱123.45")
println("PASS: 11 pricing, modifier, tender, formatting checks")
